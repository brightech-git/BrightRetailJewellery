                            + CHAR(13) + N'INTO TEMPTABLEDB..TEMP' + @SystemId + N'FINAL2'    
                            + CHAR(13) + N'FROM TEMPTABLEDB..TEMP' + @SystemId + N'FINAL'    
                            + CHAR(13) + N'WHERE BILLNO <> @P_SUBTOTAL'    
                            + CHAR(13) + N'ORDER BY SEP,BATCHNO,KEYNO'    
          PRINT @SEARCHSQL    
          EXEC sp_executesql @SEARCHSQL    
                            ,N'@P_SUBTOTAL VARCHAR(20)'    
                            ,@P_SUBTOTAL = 'SUB TOTAL'    
  
          /*  ---- turn the blank search arguments into NULL / LIKE patterns ---- */  
          /*  doing this in static T-SQL keeps the dynamic statement free of any  */  
          /*  embedded literals and lets the values travel as real parameters     */  
          SELECT @L_CUSTOMER = CASE WHEN ISNULL(@CUSTOMER    ,'') = '' THEN NULL ELSE '%' + @CUSTOMER     + '%' END    
                ,@L_PHONENO  = CASE WHEN ISNULL(@PHONENO     ,'') = '' THEN NULL ELSE '%' + @PHONENO      + '%' END    
                ,@L_PAN      = CASE WHEN ISNULL(@PAN         ,'') = '' THEN NULL ELSE '%' + @PAN          + '%' END    
                ,@L_GSTNO    = CASE WHEN ISNULL(@GSTNO       ,'') = '' THEN NULL ELSE '%' + @GSTNO        + '%' END    
                ,@L_ADDRESS  = CASE WHEN ISNULL(@ADDRESS     ,'') = '' THEN NULL ELSE '%' + @ADDRESS      + '%' END    
                ,@L_BILLNO   = CASE WHEN ISNULL(@SEARCHBILLNO,'') = '' THEN NULL ELSE '%' + @SEARCHBILLNO + '%' END    
  
          /*  ---- return the filtered result set -------------------------------- */  
          SELECT @SEARCHSQL = N'SELECT *'    
                            + CHAR(13) + N'FROM TEMPTABLEDB..TEMP' + @SystemId + N'FINAL2'    
                            + CHAR(13) + N'WHERE (@P_CUSTOMER IS NULL OR CUSTOMER LIKE @P_CUSTOMER)'    
                            + CHAR(13) + N'AND   (@P_PHONENO  IS NULL OR PHONENO  LIKE @P_PHONENO )'    
                            + CHAR(13) + N'AND   (@P_PAN      IS NULL OR PAN      LIKE @P_PAN     )'    
                            + CHAR(13) + N'AND   (@P_GSTNO    IS NULL OR GSTNO    LIKE @P_GSTNO   )'    
                            + CHAR(13) + N'AND   (@P_ADDRESS  IS NULL OR ADDRESS  LIKE @P_ADDRESS )'    
                            + CHAR(13) + N'AND   (@P_BILLNO   IS NULL OR BILLNO   LIKE @P_BILLNO  )'    
                            + CHAR(13) + N'AND   (@P_FROMDATE IS NULL OR TRANDATE >= @P_FROMDATE)'    
                            + CHAR(13) + N'AND   (@P_TODATE   IS NULL OR TRANDATE <  DATEADD(DAY,1,@P_TODATE))'    
                            + CHAR(13) + N'ORDER BY SEP,BATCHNO,KEYNO'    
          PRINT @SEARCHSQL    
          EXEC sp_executesql @SEARCHSQL    
                            ,N'@P_CUSTOMER NVARCHAR(210),@P_PHONENO NVARCHAR(60)    
                              ,@P_PAN      NVARCHAR(60) ,@P_GSTNO   NVARCHAR(60)    
                              ,@P_ADDRESS  NVARCHAR(510),@P_BILLNO  NVARCHAR(60)    
                              ,@P_FROMDATE DATE         ,@P_TODATE  DATE'    
                            ,@P_CUSTOMER = @L_CUSTOMER    
                            ,@P_PHONENO  = @L_PHONENO    
                            ,@P_PAN      = @L_PAN    
                            ,@P_GSTNO    = @L_GSTNO    
                            ,@P_ADDRESS  = @L_ADDRESS    
                            ,@P_BILLNO   = @L_BILLNO    
                            ,@P_FROMDATE = @FROMTRANDATE    
                            ,@P_TODATE   = @TOTRANDATE    
  END   