SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' LEFT JOIN TEMPTABLEDB..TEMPCOLLECT SC ON ST.GROUPCODE =SC.GROUPCODE AND ST.REGNO=SC.REGNO   AND SC.RECEIPTNO=ST.RECEIPTNO  AND SC.ENTREFNO=ST.ENTREFNO '  
IF @BASEDONMAINCOSTID='Y'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' LEFT JOIN COSTCENTRE C ON C.COSTID=SM.COSTID'   
END  
ELSE  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' LEFT JOIN COSTCENTRE C ON C.COSTID=ST.COSTID'   
END  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHERE ST.RDATE BETWEEN '''+CONVERT(VARCHAR,@FRMDATE)+''' AND '''+CONVERT(VARCHAR,@TODATE)+''''    
IF @ISCANCEL='Y'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ISNULL(ST.CANCEL,'''')<>''Y'''  
END  
IF @SCHEME<>'ALL'  
BEGIN   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND SM.SCHEMEID IN(SELECT SCHEMEID FROM SCHEME WHERE SCHEMENAME IN('''+@SCHEME+'''))'  
END  
IF @COSTNAME<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.COSTID IN (SELECT COSTID FROM COSTCENTRE WHERE COSTNAME IN ( '''+ REPLACE(@COSTNAME, ', ', ''',''') +'''))'  
END  
IF @SYSTEMID<>'''ALL'''  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(ST.SYSTEMID AS VARCHAR) IN ('+@SYSTEMID+')'  
END  
IF @GROUPCODE<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND SM.GROUPCODE IN('''+@GROUPCODE+''')'  
END             
IF @PAYMODE<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND SC.MODEPAY IN('''+@PAYMODE+''')'  
END            
IF @USERID<>'''ALL'''  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(ST.USERID AS VARCHAR) IN ('+@USERID+')'  
END  
IF @INSTALLMENT<>''  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(ST.INSTALLMENT AS VARCHAR) IN ('+ @INSTALLMENT +')'  
END  
PRINT @VERSIONTYPE  
IF @VERSIONTYPE NOT LIKE  '%ALL%'   
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ( ST.APPVER NOT IN ('''')'  
IF @VERSIONTYPE NOT LIKE  '%WEB%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER NOT IN(''WEB'') '  
IF @VERSIONTYPE NOT LIKE '%APP%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER NOT IN(''APP'') '  
IF @VERSIONTYPE NOT LIKE '%VAP%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER NOT IN(''VAP'') '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' )'  
IF @VERSIONTYPE NOT LIKE '%WEB%' AND @VERSIONTYPE NOT LIKE '%APP%' AND @VERSIONTYPE NOT LIKE '%VAP%' AND @VERSIONTYPE NOT LIKE '%HOMECOLLECT%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER NOT IN(''APP'',''WEB'',''VAP'') '  
IF @VERSIONTYPE NOT LIKE '%WINDOWS%' AND @VERSIONTYPE NOT LIKE '%HOMECOLLECT%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER IN(''APP'',''WEB'',''VAP'') '  
IF @VERSIONTYPE LIKE '%HOMECOLLECT%'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND SM.HOMECOLLECT = ''Y''  '  
/*IF @VERSIONTYPE = 'WEB'   
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER IN(''WEB'') '  
END  
IF @VERSIONTYPE = 'APP'   
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(SC.SYSTEMID AS VARCHAR) IN (''APP'')'  
End  
IF @VERSIONTYPE <> 'WEB' AND @VERSIONTYPE <> 'APP'    
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ST.APPVER NOT IN(''WEB'') '  
END */  
END  
PRINT @SQLTEXT  
EXECUTE(@SQLTEXT)  
SELECT @SQLTEXT='SELECT IDENTITY(INT, 1,1) AS ID,CASE WHEN ISNULL(P.INITIAL,'''')<>'''' THEN P.INITIAL +''.'''   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ELSE ''''END +P.PNAME +''''  AS CUSNAME,P.MOBILE,T.SNO,T.GROUPCODE,T.REGNO,T.AMOUNT,T.RECEIPTNO'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,CONVERT(DECIMAL(10,2),T.INSTALLMENT) AS INSTALLMENT,CONVERT(VARCHAR,T.RDATE,5)RDATE,T.RDATE1,T.MODEPAY,T.WEIGHT,CONVERT(VARCHAR,T.RATE)RATE, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' T.CANCEL,T.CHQBANK ,T.CHQBRANCH,T.CHQ_CARDNO, T.CHQDATE,T.USERID,T.SYSTEMID ,'            
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' CASE WHEN LEN(LTRIM(RIGHT(CONVERT(VARCHAR, T.UPTIME, 100),8)))=6 THEN  RIGHT(''0''+ LTRIM(RIGHT(CONVERT(VARCHAR, T.UPTIME, 100),8)) ,8) ELSE RIGHT(LTRIM(RIGHT(CONVERT(VARCHAR, T.UPTIME, 100),8)) ,8) END AS UPTIME,T.UPTIME1'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,ISNULL(T.MONTHWISEINS,'''')MONTHWISEINS,T.CHEQUERETDATE ,T.SCHEMENAME,T.COSTNAME,T.COLHEAD,T.RESULT,T.TCOSTID'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INTO TEMPTABLEDB..TEMPTRANVIEW FROM PERSONALINFO P,TEMPTABLEDB..TEMPTRAN T WHERE P.PERSONALID=T.SNO'  
IF @ORDERBY='GROUP'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ORDER BY GROUPCODE,REGNO'  
END  
IF @ORDERBY='DATE'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ORDER BY RDATE1,RECEIPTNO'  
END  
IF @ORDERBY ='RNO'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ORDER BY RECEIPTNO'  
END  
IF @ORDERBY ='UPTIME'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ORDER BY T.RDATE1,T.UPTIME1 '  
END  
PRINT @SQLTEXT  
EXECUTE(@SQLTEXT)            
SELECT @SQLTEXT=' SELECT MODEPAY, SUM(AMOUNT) AS CASHAMOUNT'              
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(AMOUNT)ELSE 0 END AS CANCELAMT'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,SUM(WEIGHT) AS WEIGHT, CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(WEIGHT)ELSE 0 END AS CANCELWGT'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,SCHEMENAME  INTO TEMPTABLEDB..TEMPMODEWISE '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM TEMPTABLEDB..TEMPTRANVIEW GROUP BY SCHEMENAME, MODEPAY , CANCEL'  
PRINT @SQLTEXT  
EXECUTE(@SQLTEXT)  
SELECT @NOOFRECORDS=COUNT(*)FROM TEMPTABLEDB..TEMPTRANVIEW  
IF @NOOFRECORDS=0  
BEGIN  
RETURN  
END  
DECLARE CUR1 CURSOR FOR SELECT  ID FROM TEMPTABLEDB..TEMPTRANVIEW ORDER BY ID  
OPEN CUR1  
FETCH NEXT FROM CUR1 INTO @RESULT  
WHILE @@FETCH_STATUS<>-1  
BEGIN  
UPDATE TEMPTABLEDB..TEMPTRANVIEW SET COLHEAD=@COLHEAD WHERE ID=@RESULT   
SELECT @INDEX=@INDEX+1  
IF @INDEX=@LINESPERPAGE  
BEGIN  
SELECT @COLHEAD=@COLHEAD+1  
SELECT @INDEX=0  
END  
FETCH NEXT FROM CUR1 INTO @RESULT  
END  
CLOSE CUR1  
DEALLOCATE CUR1  
IF OBJECT_ID('TEMPTABLEDB..TEMPRECISS','U') IS NOT NULL  DROP TABLE TEMPTABLEDB..TEMPRECISS   
SELECT @SQLTEXT= ' SELECT * INTO TEMPTABLEDB..TEMPRECISS FROM('  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT R.PAYMODE,ISNULL(SUM(CASE WHEN R.TRANTYPE = ''R'' THEN R.AMOUNT ELSE 0 END),0) AS RECEIPT,'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ISNULL(SUM(CASE WHEN R.TRANTYPE = ''P'' THEN R.AMOUNT ELSE 0 END),0) AS PAYMENT'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM RECPAY R '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INNER JOIN RTMsh0708..SCHEMETRAN ST ON ST.ENTREFNO=R.ENTREFNO '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INNER JOIN SCHEMEMAST  M ON ST.GROUPCODE=M.GROUPCODE AND ST.REGNO=M.REGNO '  
IF @SCHEME<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND M.SCHEMEID IN(SELECT SCHEMEID FROM SCHEME WHERE SCHEMENAME IN('''+@SCHEME+'''))'  
END  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHERE R.TRANDATE BETWEEN '''+CONVERT(VARCHAR,@FRMDATE)+''' AND '''+CONVERT(VARCHAR,@TODATE)+''''   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ISNULL(R.CANCEL,'''') <> ''Y'' '  
IF @COSTNAME<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND R.COSTID IN (SELECT COSTID FROM COSTCENTRE WHERE COSTNAME IN ( '''+ REPLACE(@COSTNAME, ', ', ''',''') +'''))'  
END  
IF @SYSTEMID<>'''ALL'''  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(R.SYSTEMID AS VARCHAR) IN ('+@SYSTEMID+')'  
END  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' GROUP BY R.PAYMODE '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT R.PAYMODE,ISNULL(SUM(CASE WHEN R.TRANTYPE = ''R'' THEN R.AMOUNT ELSE 0 END),0) AS RECEIPT,'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ISNULL(SUM(CASE WHEN R.TRANTYPE = ''P'' THEN R.AMOUNT ELSE 0 END),0) AS PAYMENT '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM RECPAY R '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INNER JOIN SCHEMEMAST  M ON R.GROUPCODE=M.GROUPCODE AND R.REGNO=M.REGNO '  
IF @SCHEME<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND M.SCHEMEID IN(SELECT SCHEMEID FROM SCHEME WHERE SCHEMENAME IN('''+@SCHEME+'''))'  
END  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHERE R.TRANDATE BETWEEN '''+CONVERT(VARCHAR,@FRMDATE)+''' AND '''+CONVERT(VARCHAR,@TODATE)+''''   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ISNULL(R.CANCEL,'''') <> ''Y'' '  
IF @COSTNAME<>'ALL'  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND R.COSTID IN (SELECT COSTID FROM COSTCENTRE WHERE COSTNAME IN ( '''+ REPLACE(@COSTNAME, ', ', ''',''') +'''))'  
END  
IF @SYSTEMID<>'''ALL'''  
BEGIN  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND CAST(R.SYSTEMID AS VARCHAR) IN ('+@SYSTEMID+')'  
END  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' GROUP BY R.PAYMODE '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT R.PAYMODE,ISNULL(SUM(CASE WHEN R.TRANTYPE = ''R'''   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' THEN R.AMOUNT ELSE 0 END),0) AS RECEIPT, ISNULL(SUM(CASE WHEN R.TRANTYPE = ''P'''  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' THEN R.AMOUNT ELSE 0 END),0) AS PAYMENT FROM RECPAY R  '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHERE R.TRANDATE BETWEEN '''+CONVERT(VARCHAR,@FRMDATE)+''' AND '''+CONVERT(VARCHAR,@TODATE)+''''   
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ISNULL(R.PAYMODE,'''')='''''  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND ISNULL(R.GROUPCODE,'''')='''' AND ISNULL(R.REGNO,0)=0'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' GROUP BY R.PAYMODE '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' )X ORDER BY X.PAYMODE'  
PRINT @SQLTEXT   
EXEC (@SQLTEXT)  
DECLARE @SQLTEXT_TEMP AS VARCHAR(1000)  
SELECT @SQLTEXT_TEMP=' IF OBJECT_ID(''T1'',''U'') IS NOT NULL  DROP TABLE T1 '  
SELECT @SQLTEXT_TEMP=@SQLTEXT_TEMP+ CHAR(13)+' CREATE TABLE T1(PAYMODE VARCHAR(10),RECEIPT FLOAT, PAYMENT  FLOAT)'      
SELECT @SQLTEXT_TEMP=@SQLTEXT_TEMP+ CHAR(13)+' INSERT INTO T1 EXEC SP_RECPAY @QRY = ''SELECT * FROM TEMPTABLEDB..TEMPRECISS'' '            
PRINT @SQLTEXT_TEMP  
EXEC (@SQLTEXT_TEMP)  
SELECT @SQLTEXT=' ALTER TABLE TEMPTABLEDB..TEMPTRANVIEW ALTER COLUMN GROUPCODE VARCHAR(100)'            
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ALTER TABLE TEMPTABLEDB..TEMPTRANVIEW ALTER COLUMN MODEPAY VARCHAR(100)'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ALTER TABLE TEMPTABLEDB..TEMPTRANVIEW ALTER COLUMN AMOUNT  NUMERIC '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ALTER TABLE TEMPTABLEDB..TEMPTRANVIEW ALTER COLUMN RECEIPTNO  NUMERIC '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ALTER TABLE TEMPTABLEDB..TEMPTRANVIEW ALTER COLUMN WEIGHT  NUMERIC(18,3)'            
PRINT @SQLTEXT  
EXECUTE(@SQLTEXT)  
SELECT @SQLTEXT=' INSERT INTO TEMPTABLEDB..TEMPTRANVIEW(CUSNAME,AMOUNT,RECEIPTNO,INSTALLMENT,RATE,MODEPAY,WEIGHT,MONTHWISEINS,RESULT,COLHEAD)'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT ''SUB TOTAL  =>'',SUM(GROSSAMT)GROSSAMT,SUM(CANCELAMT)CANCELAMT,(SUM(GROSSAMT)-SUM(CANCELAMT))NETAMT '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,SUM(GROSSWGT)GROSSWGT,SUM(CANCELWGT)CANCELWGT,(SUM(GROSSWGT)-SUM(CANCELWGT))NETWGT,'''',2 RESULT,COLHEAD'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM ( SELECT   SUM(AMOUNT)AS GROSSAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(AMOUNT)ELSE 0 END AS CANCELAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SUM(WEIGHT)AS GROSSWGT,CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(WEIGHT)ELSE 0 END AS CANCELWGT,COLHEAD '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM TEMPTABLEDB..TEMPTRANVIEW WHERE  RESULT =0 GROUP BY COLHEAD,CANCEL)X GROUP BY COLHEAD '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT ''GRAND TOTAL=>'',SUM(GROSSAMT)GROSSAMT,SUM(CANCELAMT)CANCELAMT,(SUM(GROSSAMT)-SUM(CANCELAMT))NETAMT'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,SUM(GROSSWGT),SUM(CANCELWGT),(SUM(GROSSWGT)-SUM(CANCELWGT))NETWGT,'''',4 RESULT, ''9999'''  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM ( SELECT   SUM(AMOUNT)AS GROSSAMT,'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(AMOUNT)ELSE 0 END AS CANCELAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SUM(WEIGHT)AS GROSSWGT,CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(WEIGHT)ELSE 0 END AS CANCELWGT,COLHEAD '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM TEMPTABLEDB..TEMPTRANVIEW WHERE  RESULT=0 GROUP BY COLHEAD,CANCEL)X'  
/*SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT TOP 1 ''''GROUPCODE,0,0,0,0,0,0,'''' MONTHWISEINS,5 RESULT,''99999''COLHEAD FROM TEMPTABLEDB..TEMPTRANVIEW   '*/  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT TOP 1 ''COLLECTION SUMMARY'',0,0,0,0,0,0,''''MONTHWISEINS,6 RESULT,''9999''COLHEAD FROM TEMPTABLEDB..TEMPTRANVIEW   '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INSERT INTO TEMPTABLEDB..TEMPTRANVIEW(CUSNAME,AMOUNT,RECEIPTNO,INSTALLMENT,RATE,MODEPAY,WEIGHT,MONTHWISEINS,RESULT'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,COLHEAD) SELECT CASE MODEPAY '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHEN ''C'' THEN ''CASH AMOUNT'' WHEN ''D'' THEN ''CHEQUE AMOUNT'' WHEN ''R''THEN ''CREDITCARD AMOUNT'' WHEN ''E'' THEN ''E-TRANSFER AMOUNT'' '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' WHEN ''O'' THEN ''OTHER AMOUNT'' WHEN ''A'' THEN ''ADVANCE AMOUNT'' WHEN ''G'' THEN ''GIFT VOUCHER'' WHEN ''P'' THEN ''CREDIT PURCHASE'' ELSE ''''  END AS MODEPAY'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,ISNULL(SUM(GROSSAMT),0)GROSSAMT,ISNULL(SUM(CANCELAMT),0)CANCELAMT,ISNULL(SUM(GROSSAMT),0)-ISNULL(SUM(CANCELAMT),0)NETAMOUNT,'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ISNULL(SUM(GROSSWGT),0)GROSSWGT,CONVERT(VARCHAR,ISNULL(SUM(CANCELWGT),0))CANCELWGT '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' ,ISNULL(SUM(GROSSWGT),0)-ISNULL(SUM(CANCELWGT),0)NETAMOUNT,'''',8,''9999'' '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM (SELECT SUM(AMOUNT)AS GROSSAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(AMOUNT)ELSE 0 END AS CANCELAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SUM(WEIGHT)AS GROSSWGT,CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(WEIGHT)ELSE 0 END AS CANCELWGT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' MODEPAY FROM TEMPTABLEDB..TEMPTRANVIEW WHERE RESULT =0'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' GROUP BY MODEPAY,CANCEL )X GROUP BY MODEPAY '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT ''TOTAL AMOUNT'', SUM(GROSSAMT)GROSSAMT,SUM(CANCELAMT)CANCELAMT,SUM(GROSSAMT)-SUM(CANCELAMT)NETAMOUNT,'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SUM(GROSSWGT)GROSSWGT,CONVERT(VARCHAR,SUM(CANCELWGT))CANCELWGT ,SUM(GROSSWGT)-SUM(CANCELWGT)NETAMOUNT,'''',9,''9999'' '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' FROM (SELECT SUM(AMOUNT)AS GROSSAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(AMOUNT)ELSE 0 END AS CANCELAMT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SUM(WEIGHT)AS GROSSWGT,CASE ISNULL(CANCEL,'''') WHEN ''Y'' THEN SUM(WEIGHT)ELSE 0 END AS CANCELWGT, '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' MODEPAY FROM TEMPTABLEDB..TEMPTRANVIEW WHERE RESULT =0'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' GROUP BY MODEPAY,CANCEL )X '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' INSERT INTO TEMPTABLEDB..TEMPTRANVIEW(CUSNAME,INSTALLMENT,WEIGHT,MONTHWISEINS,RESULT,COLHEAD)'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT TOP 1 '''',0,0,'''',12 RESULT,''99999'' FROM TEMPTABLEDB..TEMPTRANVIEW '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' UNION ALL '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' SELECT TOP 1 ''CREDIT COLLECTION'',0,0,'''',16 RESULT,''99999'' FROM TEMPTABLEDB..TEMPTRANVIEW '  
