ALTER PROCEDURE [dbo].[SP_TRANVIEW]
(  
@LINESPERPAGE INT,  
@ISCANCEL VARCHAR(1),  
@SCHEME VARCHAR(300),  
@COSTNAME VARCHAR(200),  
@SYSTEMID VARCHAR(200),  
@GROUPCODE VARCHAR(200),  
@USERID VARCHAR(200),  
@FRMDATE VARCHAR(12),  
@TODATE VARCHAR(12),  
@WITHSCHDENOMI VARCHAR(3),  
@BASEDONMAINCOSTID VARCHAR(3),  
@ORDERBY VARCHAR(50),  
@DETAILEDVIEW VARCHAR(1),  
@PAYMODE VARCHAR(50),@VERSIONTYPE  VARCHAR(50),@INSTALLMENT VARCHAR(5)  
)  
AS  
BEGIN  
DECLARE @SQLTEXT VARCHAR(8000)  
DECLARE @RESULT INT   
DECLARE @INDEX INT  
DECLARE @COLHEAD INT  
DECLARE @NOOFRECORDS INT  
SET @SCHEME=REPLACE(@SCHEME,',',''',''')   
SET @GROUPCODE=REPLACE(@GROUPCODE,',',''',''')   
SET @PAYMODE=REPLACE(@PAYMODE,',',''',''')   
SELECT @INDEX=0  
SELECT @COLHEAD=1  
SELECT @NOOFRECORDS=0  
SET @SYSTEMID = ''''+REPLACE(@SYSTEMID,',',''',''')+''''  
SET @USERID  = ''''+REPLACE(@USERID,',',''',''')+''''  
SET @VERSIONTYPE  = ''''+REPLACE(@VERSIONTYPE,',',''',''')+''''    
