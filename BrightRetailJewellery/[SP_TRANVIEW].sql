EXECUTE(@SQLTEXT)  
SELECT @SQLTEXT='SELECT SM.COSTID AS MCOSTID,ST.COSTID AS TCOSTID,SM.SNO,ST.GROUPCODE,ST.REGNO'  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+',CAST((CASE  WHEN (SELECT COUNT(RECEIPTNO)FROM RTMsh0708..SCHEMECOLLECT WHERE ST.GROUPCODE = GROUPCODE AND ST.REGNO= REGNO   AND  RECEIPTNO=ST.RECEIPTNO)>1 THEN SC.AMOUNT ELSE  ST.AMOUNT END) AS DECIMAL(12,2)) AMOUNT'
  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+',ST.RECEIPTNO,CAST(ST.INSTALLMENT AS DECIMAL(18,2))INSTALLMENT,CONVERT(VARCHAR,SC.RDATE,5)RDATE,SC.RDATE AS RDATE1, SC.MODEPAY'   
