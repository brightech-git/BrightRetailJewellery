SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' AND  RECEIPTNO=ST.RECEIPTNO )>1 THEN SC.AMOUNT/ST.RATE ELSE  ST.WEIGHT END)ELSE ST.WEIGHT '  
SELECT @SQLTEXT=@SQLTEXT+ CHAR(13)+' END)AS DECIMAL(12,3)) WEIGHT'  
