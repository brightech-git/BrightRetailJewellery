SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,2),NULL) TAGVALUE,I.AMOUNT AS AMOUNT,NULL STNAMT'  
SELECT @QRY= @QRY + CHAR(13) +',I.DISCOUNT,I.FIN_DISCOUNT,I.FIN_PURDISCOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',E.EMPNAME AS SALESMAN'  
SELECT @QRY= @QRY + CHAR(13) +',E1.EMPNAME AS AUTHORIZE,BATCHNO'  
SELECT @QRY= @QRY + CHAR(13) +',I.RATE,I.TAGDESIGNER,I.ITEMCTRID,IM.STOCKTYPE,''D''AS COLHEAD'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) MAXWASTPER '  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) MAXMCGRM'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) MAXWAST'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) MC'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) MAXMC'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(20,3),NULL) WASTAGE,1 AS RESULT'  
SELECT @QRY= @QRY + CHAR(13) +',(SELECT TOP 1 REMARK1 FROM '+@ADMINDB+'..CUSTOMERINFO WHERE BATCHNO=I.BATCHNO) REMARK'   
SELECT @QRY= @QRY + CHAR(13) +'INTO TEMPTABLEDB..'+@TEMPTABLE+' FROM ISSUE AS I'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..ITEMMAST AS IM ON IM.ITEMID=I.ITEMID'  
SELECT @QRY= @QRY + CHAR(13) +'LEFT JOIN '+@ADMINDB+'..SUBITEMMAST AS SI ON SI.SUBITEMID=I.SUBITEMID'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..METALMAST AS M ON M.METALID=I.METALID'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..EMPMASTER AS E ON E.EMPID=I.EMPID '  
SELECT @QRY= @QRY + CHAR(13) +'LEFT JOIN '+@ADMINDB+'..EMPMASTER AS E1 ON E1.EMPID=I.DISC_EMPID'  
SELECT @QRY= @QRY + CHAR(13) +'WHERE I.TRANDATE BETWEEN  '''+@FROMDATE+''' AND '''+@TODATE+''''  
SELECT @QRY= @QRY + CHAR(13) +'AND I.COMPANYID IN('''+@COMPANYID+''')'  
SELECT @QRY= @QRY + CHAR(13) +'AND ISNULL(I.CANCEL,'''')='''''  
IF @COSTID<>'ALL'  
BEGIN  
