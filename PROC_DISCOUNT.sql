SELECT @QRY= @QRY + CHAR(13) +'FROM '+@ADMINDB+'..ITEMNONTAG  W,TEMPTABLEDB..'+@TEMPTABLE+' T'  
SELECT @QRY= @QRY + CHAR(13) +'WHERE W.ITEMID  = T.ITEMID  AND T.STOCKTYPE =''N'' '  
SELECT @QRY= @QRY + CHAR(13) +'AND T.SUBITEMID = W.SUBITEMID AND T.TAGDESIGNER =W.DESIGNERID '  
SELECT @QRY= @QRY + CHAR(13) +'AND T.ITEMCTRID = W.ITEMCTRID AND W.RECISS =''R'''  
