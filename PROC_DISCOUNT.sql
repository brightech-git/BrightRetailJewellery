ALTER PROCEDURE PROC_DISCOUNT  
(  
@ADMINDB VARCHAR(15),  
@DBNAME VARCHAR(15),  
@FROMDATE VARCHAR(30),  
@TODATE VARCHAR(30),  
@COMPANYID VARCHAR(500),  
@TEMPTABLE VARCHAR(50),  
@COSTID VARCHAR(500),  
@METALID VARCHAR(500),            
@GROUPBY VARCHAR(1),  
@WITHEX VARCHAR(1)  
)  
AS   
BEGIN  
DECLARE @QRY VARCHAR(8000)  
SET @COSTID = REPLACE(@COSTID,',',''',''')  
SET @METALID = REPLACE(@METALID,',',''',''')  
SET @COMPANYID = ''+REPLACE(@COMPANYID,',',''',''')+''  
SELECT @QRY= 'IF  EXISTS (SELECT * FROM TEMPTABLEDB..SYSOBJECTS WHERE XTYPE = ''U'' AND NAME = '''+@TEMPTABLE+''' )DROP TABLE TEMPTABLEDB..'+@TEMPTABLE+' '  
EXEC (@QRY)  
IF @WITHEX = 'Y'  
BEGIN  
SELECT @QRY= CHAR(13) +'SELECT CONVERT(VARCHAR(20),BILLNO)BILLNO ,BILLDATE,METAL,GRSWT,NETWT,AMOUNT,SUM(DISCLIMITAMT)DISCLIMITAMT,SUM(DISCALLOWAMT)DISCALLOWAMT,DISCOUNT,OFFERDISC,FINALDISC AS FINALDISC,FINALPURDISC AS FINALPURDISC'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(ISNULL(DISCOUNT,0))+SUM(ISNULL(OFFERDISC,0))+SUM(ISNULL(FINALDISC,0))TOTALDISC '  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(15,2),CASE WHEN AMOUNT<>0 THEN (((SUM(ISNULL(DISCOUNT,0))+SUM(ISNULL(FINALDISC,0))+SUM(ISNULL(OFFERDISC,0)))*100)/AMOUNT)END) AS DISCPER'  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,REMARK,COLHEAD,RESULT'  
SELECT @QRY= @QRY + CHAR(13) +',IDENTITY (INT,1,1)SNO INTO TEMPTABLEDB..'+@TEMPTABLE+' '  
SELECT @QRY= @QRY + CHAR(13) +'FROM('  
SELECT @QRY= @QRY + CHAR(13) +'SELECT  BILLNO'  
SELECT @QRY= @QRY + CHAR(13) +',BILLDATE,METAL,SUM(GRSWT) AS GRSWT,SUM(NETWT) AS NETWT'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(AMOUNT) AS AMOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(15,2),SUM(ISNULL(DISCOUNT1,0))) AS DISCOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(DISCOUNT) AS OFFERDISC'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(FIN_DISCOUNT) AS FINALDISC'
SELECT @QRY= @QRY + CHAR(13) +',SUM(FIN_PURDISCOUNT) AS FINALPURDISC'
SELECT @QRY= @QRY + CHAR(13) +' ,(SELECT SUM(DISCLIMITAMT) FROM DISCHISTORY D WHERE D.BATCHNO IN '  
SELECT @QRY= @QRY + CHAR(13) +' (SELECT BATCHNO FROM '+@ADMINDB+'..EXEMPTION AS EX WHERE EX.BATCHNO=X.BATCHNO '  
SELECT @QRY= @QRY + CHAR(13) +' AND EX.OPTIONID=''6'' ))DISCLIMITAMT '  
SELECT @QRY= @QRY + CHAR(13) +' ,(SELECT SUM(DISCALLOWAMT) FROM DISCHISTORY D WHERE D.BATCHNO IN '  
SELECT @QRY= @QRY + CHAR(13) +' (SELECT BATCHNO FROM '+@ADMINDB+'..EXEMPTION AS EX WHERE EX.BATCHNO=X.BATCHNO  '  
SELECT @QRY= @QRY + CHAR(13) +' AND EX.OPTIONID=''6'' ))DISCALLOWAMT '  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,REMARK, CONVERT(VARCHAR,'''') AS COLHEAD,''1'' AS RESULT '  
SELECT @QRY= @QRY + CHAR(13) +'FROM('  
SELECT @QRY= @QRY + CHAR(13) +'SELECT I.TRANNO AS BILLNO,I.TRANDATE AS BILLDATE,METALNAME AS METAL,I.GRSWT AS GRSWT,I.NETWT AS NETWT,'  
SELECT @QRY= @QRY + CHAR(13) +'I.AMOUNT AS AMOUNT,'  
SELECT @QRY= @QRY + CHAR(13) +'I.DISCOUNT,I.FIN_DISCOUNT,I.FIN_PURDISCOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',E.EMPNAME AS SALESMAN'  
SELECT @QRY= @QRY + CHAR(13) +',E1.EMPNAME AS AUTHORIZE,I.BATCHNO'  
SELECT @QRY= @QRY + CHAR(13) +',(SELECT SUM(AMOUNT) FROM ACCTRAN WHERE BATCHNO=I.BATCHNO AND TRANMODE=''D'' AND PAYMODE=''DI'')/(SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE COUNT(*) END FROM ISSUE AS Q WHERE Q.BATCHNO=I.BATCHNO)DISCOUNT1'  
SELECT @QRY= @QRY + CHAR(13) +',(SELECT TOP 1 REMARK1 FROM '+@ADMINDB+'..CUSTOMERINFO WHERE BATCHNO=I.BATCHNO) REMARK'   
SELECT @QRY= @QRY + CHAR(13) +'FROM ISSUE AS I'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..METALMAST AS M ON M.METALID=I.METALID'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..EMPMASTER AS E ON E.EMPID=I.EMPID '  
SELECT @QRY= @QRY + CHAR(13) +'LEFT JOIN '+@ADMINDB+'..EMPMASTER AS E1 ON E1.EMPID=I.DISC_EMPID'   
SELECT @QRY= @QRY + CHAR(13) +'WHERE I.TRANDATE BETWEEN  '''+@FROMDATE+''' AND '''+@TODATE+''''  
SELECT @QRY= @QRY + CHAR(13) +'AND I.COMPANYID IN('''+@COMPANYID+''')'  
SELECT @QRY= @QRY + CHAR(13) +'AND ISNULL(I.CANCEL,'''')='''''  
IF @COSTID<>'ALL'  
BEGIN  
SELECT @QRY= @QRY + CHAR(13) +' AND I.COSTID IN('''+@COSTID+''') '  
END  
IF @METALID<>'ALL'  
BEGIN  
SELECT @QRY= @QRY + CHAR(13) +' AND I.METALID IN('''+@METALID+''') '  
END  
SELECT @QRY= @QRY + CHAR(13) +')X'  
SELECT @QRY= @QRY + CHAR(13) +'GROUP BY BILLNO,BILLDATE,METAL,SALESMAN,AUTHORIZE,BATCHNO,REMARK '  
SELECT @QRY= @QRY + CHAR(13) +')Z'  
SELECT @QRY= @QRY + CHAR(13) +'GROUP BY BILLNO,BILLDATE,METAL,GRSWT,NETWT,AMOUNT,DISCOUNT,OFFERDISC,FINALDISC,FINALPURDISC'  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,COLHEAD,RESULT,REMARK '  
SELECT @QRY= @QRY + CHAR(13) +'ORDER BY BILLDATE,BILLNO'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY=  'INSERT INTO TEMPTABLEDB..'+@TEMPTABLE+'(BILLNO,GRSWT,NETWT,AMOUNT,DISCOUNT,DISCLIMITAMT,DISCALLOWAMT,OFFERDISC,FINALDISC,FINALPURDISC,TOTALDISC,COLHEAD,RESULT)'  
SELECT @QRY= @QRY + CHAR(13) +'SELECT ''GRAND TOTAL'' AS BILLNO ,SUM(GRSWT),SUM(NETWT),SUM(AMOUNT)'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(DISCOUNT),SUM(DISCLIMITAMT),SUM(DISCALLOWAMT),SUM(OFFERDISC),SUM(FINALDISC),SUM(FINALPURDISC),SUM(TOTALDISC)'  
SELECT @QRY= @QRY + CHAR(13) +',''G'' AS COLHEAD,''2'' AS RESULT FROM TEMPTABLEDB..'+@TEMPTABLE+' WHERE RESULT=1 HAVING COUNT(BILLNO)>1'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY= 'UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET DISCOUNT=NULL WHERE DISCOUNT=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET OFFERDISC=NULL WHERE OFFERDISC=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET FINALDISC=NULL WHERE FINALDISC=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET FINALPURDISC=NULL WHERE FINALPURDISC=0'
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET TOTALDISC=NULL WHERE TOTALDISC=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET AMOUNT=NULL WHERE AMOUNT=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET DISCLIMITAMT=NULL WHERE DISCLIMITAMT=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET DISCALLOWAMT=NULL WHERE DISCALLOWAMT=0'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY= 'SELECT * FROM TEMPTABLEDB..'+@TEMPTABLE+' ORDER BY SNO'  
PRINT @QRY  
EXEC (@QRY)  
END  
ELSE  
BEGIN  
IF @GROUPBY='N'  
BEGIN  
SELECT @QRY= CHAR(13) +'SELECT CONVERT(VARCHAR(20),BILLNO)BILLNO ,BILLDATE,METAL,GRSWT,NETWT,AMOUNT,DISCOUNT,OFFERDISC,FINALDISC,FINALPURDISC,'  
SELECT @QRY= @QRY + CHAR(13) +'SUM(ISNULL(DISCOUNT,0))+SUM(ISNULL(OFFERDISC,0))+SUM(ISNULL(FINALDISC,0))TOTALDISC'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(15,2),CASE WHEN AMOUNT<>0 THEN (((SUM(ISNULL(DISCOUNT,0))+SUM(ISNULL(OFFERDISC,0))+SUM(ISNULL(FINALDISC,0)))*100)/AMOUNT)END) AS DISCPER'  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,REMARK,COLHEAD,RESULT'  
SELECT @QRY= @QRY + CHAR(13) +',IDENTITY (INT,1,1)SNO INTO TEMPTABLEDB..'+@TEMPTABLE+' '  
SELECT @QRY= @QRY + CHAR(13) +'FROM('  
SELECT @QRY= @QRY + CHAR(13) +'SELECT  BILLNO'  
SELECT @QRY= @QRY + CHAR(13) +',BILLDATE,METAL,SUM(GRSWT) AS GRSWT,SUM(NETWT) AS NETWT'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(AMOUNT) AS AMOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',CONVERT(NUMERIC(15,2),SUM(ISNULL(DISCOUNT1,0))) AS DISCOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(DISCOUNT) AS OFFERDISC,SUM(FIN_DISCOUNT) AS FINALDISC,SUM(FIN_PURDISCOUNT) AS FINALPURDISC'  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,REMARK, CONVERT(VARCHAR,'''') AS COLHEAD,''1'' AS RESULT '  
SELECT @QRY= @QRY + CHAR(13) +'FROM('  
SELECT @QRY= @QRY + CHAR(13) +'SELECT I.TRANNO AS BILLNO,I.TRANDATE AS BILLDATE,METALNAME AS METAL,I.GRSWT AS GRSWT,I.NETWT AS NETWT,'  
SELECT @QRY= @QRY + CHAR(13) +'I.AMOUNT AS AMOUNT'  
SELECT @QRY= @QRY + CHAR(13) +',I.DISCOUNT,I.FIN_DISCOUNT,I.FIN_PURDISCOUNT '  
SELECT @QRY= @QRY + CHAR(13) +',E.EMPNAME AS SALESMAN'  
SELECT @QRY= @QRY + CHAR(13) +',E1.EMPNAME AS AUTHORIZE,BATCHNO'  
SELECT @QRY= @QRY + CHAR(13) +',(SELECT SUM(AMOUNT) FROM ACCTRAN WHERE BATCHNO=I.BATCHNO AND TRANMODE=''D'' AND PAYMODE=''DI'')/(SELECT CASE WHEN COUNT(*)=0 THEN 1 ELSE COUNT(*) END FROM ISSUE AS Q WHERE Q.BATCHNO=I.BATCHNO)DISCOUNT1'  
SELECT @QRY= @QRY + CHAR(13) +',(SELECT TOP 1 REMARK1 FROM '+@ADMINDB+'..CUSTOMERINFO WHERE BATCHNO=I.BATCHNO) REMARK'   
SELECT @QRY= @QRY + CHAR(13) +'FROM ISSUE AS I'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..METALMAST AS M ON M.METALID=I.METALID'  
SELECT @QRY= @QRY + CHAR(13) +'INNER JOIN '+@ADMINDB+'..EMPMASTER AS E ON E.EMPID=I.EMPID '  
SELECT @QRY= @QRY + CHAR(13) +'LEFT JOIN '+@ADMINDB+'..EMPMASTER AS E1 ON E1.EMPID=I.DISC_EMPID'   
SELECT @QRY= @QRY + CHAR(13) +'WHERE I.TRANDATE BETWEEN  '''+@FROMDATE+''' AND '''+@TODATE+''''  
SELECT @QRY= @QRY + CHAR(13) +'AND I.COMPANYID IN('''+@COMPANYID+''')'  
SELECT @QRY= @QRY + CHAR(13) +'AND ISNULL(I.CANCEL,'''')='''''  
IF @COSTID<>'ALL'  
BEGIN  
SELECT @QRY= @QRY + CHAR(13) +'AND I.COSTID IN('''+@COSTID+''')'  
END  
IF @METALID<>'ALL'  
BEGIN  
SELECT @QRY= @QRY + CHAR(13) +' AND I.METALID IN('''+@METALID+''') '  
END            
SELECT @QRY= @QRY + CHAR(13) +')X'  
SELECT @QRY= @QRY + CHAR(13) +'GROUP BY BILLNO,BILLDATE,METAL,SALESMAN,AUTHORIZE,BATCHNO,REMARK '  
SELECT @QRY= @QRY + CHAR(13) +')Z'  
SELECT @QRY= @QRY + CHAR(13) +'GROUP BY BILLNO,BILLDATE,METAL,GRSWT,NETWT,AMOUNT,DISCOUNT,FINALDISC,FINALPURDISC,OFFERDISC'  
SELECT @QRY= @QRY + CHAR(13) +',SALESMAN,AUTHORIZE,COLHEAD,RESULT,REMARK '  
SELECT @QRY= @QRY + CHAR(13) +'ORDER BY BILLDATE,BILLNO'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY=  'INSERT INTO TEMPTABLEDB..'+@TEMPTABLE+'(BILLNO,GRSWT,NETWT,AMOUNT,DISCOUNT,OFFERDISC,FINALDISC,FINALPURDISC,TOTALDISC,COLHEAD,RESULT)'  
SELECT @QRY= @QRY + CHAR(13) +'SELECT ''GRAND TOTAL'' AS BILLNO ,SUM(GRSWT),SUM(NETWT),SUM(AMOUNT)'  
SELECT @QRY= @QRY + CHAR(13) +',SUM(DISCOUNT),SUM(OFFERDISC),SUM(FINALDISC),SUM(FINALPURDISC),SUM(TOTALDISC)'  
SELECT @QRY= @QRY + CHAR(13) +',''G'' AS COLHEAD,''2'' AS RESULT FROM TEMPTABLEDB..'+@TEMPTABLE+' WHERE RESULT=1 HAVING COUNT(BILLNO)>1'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY= 'UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET DISCOUNT=NULL WHERE DISCOUNT=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET OFFERDISC=NULL WHERE OFFERDISC=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET FINALDISC=NULL WHERE FINALDISC=0'
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET FINALPURDISC=NULL WHERE FINALPURDISC=0'		   
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET TOTALDISC=NULL WHERE TOTALDISC=0'  
SELECT @QRY= @QRY + CHAR(13) +' UPDATE TEMPTABLEDB..'+@TEMPTABLE+' SET AMOUNT=NULL WHERE AMOUNT=0'  
PRINT @QRY  
EXEC (@QRY)  
SELECT @QRY= 'SELECT * FROM TEMPTABLEDB..'+@TEMPTABLE+' ORDER BY SNO'  
PRINT @QRY  
EXEC (@QRY)  
END  
ELSE  
BEGIN  
SELECT @QRY=  CHAR(13) +'SELECT I.SNO,I.TRANNO AS BILLNO,I.TRANDATE AS BILLDATE'  
SELECT @QRY= @QRY + CHAR(13) +',I.TAGNO,I.ITEMID,I.SUBITEMID'  
